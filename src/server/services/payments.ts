import "server-only";
import { z } from "zod";
import { Prisma } from "@/generated/prisma/client";
import { businessDate, ymd } from "@/lib/business-date";
import { CURRENCY_CODES } from "@/lib/labels";
import { assertPermission, hasPermission, type Principal } from "@/server/auth/principal";
import { invoiceScope, paymentScope } from "@/server/auth/scope";
import { getDb } from "@/server/db";
import { deriveInvoiceStatus } from "@/server/domain/invoice-status";
import { D, isoDate, positiveAmount } from "@/server/domain/money";
import { AppError, conflict, invalid, isUniqueViolation, mapDatabaseError, notFound } from "@/server/errors";
import { listQuery, paged, skipTake } from "@/server/query";
import { withTransactionRetry, type RetryOptions } from "@/server/retry";

export const PAYMENT_METHODS = ["CASH", "BANK_TRANSFER", "CARD", "OTHER"] as const;

export const recordPaymentSchema = z
  .object({
    invoiceId: z.uuid(),
    amount: positiveAmount,
    /** Optional; when sent it must equal the invoice currency. */
    currencyCode: z.enum(CURRENCY_CODES).optional(),
    paymentDate: isoDate,
    method: z.enum(PAYMENT_METHODS),
    reference: z.string().trim().max(120).optional(),
    /** Generated by the client once per payment form; reused on every retry of that submission. */
    idempotencyKey: z.string().trim().min(8).max(100),
  })
  .refine((v) => v.method === "CASH" || !!v.reference, { message: "A reference is required for non-cash payments.", path: ["reference"] });

export type RecordPaymentInput = z.output<typeof recordPaymentSchema>;

const PAYMENT_SELECT = {
  id: true,
  invoiceId: true,
  amount: true,
  currencyCode: true,
  paymentDate: true,
  method: true,
  reference: true,
  idempotencyKey: true,
  createdAt: true,
  recordedBy: { select: { email: true, employee: { select: { firstName: true, lastName: true } } } },
} satisfies Prisma.PaymentSelect;

type PaymentRow = Prisma.PaymentGetPayload<{ select: typeof PAYMENT_SELECT }>;

/* --------------------------------------------------------------- list */

export const paymentListQuery = listQuery(["paymentDate", "amount", "createdAt"] as const, "paymentDate", "desc").extend({
  method: z.enum(PAYMENT_METHODS).optional(),
  currency: z.enum(CURRENCY_CODES).optional(),
  invoiceId: z.uuid().optional(),
  customerId: z.uuid().optional(),
  from: z.iso.date().optional(),
  to: z.iso.date().optional(),
});
export type PaymentListQuery = z.output<typeof paymentListQuery>;

/** Payments visible to the caller (representatives: payments on their scoped invoices). */
export async function listPayments(p: Principal, query: PaymentListQuery = paymentListQuery.parse({})) {
  assertPermission(p, "payments.view");
  const where: Prisma.PaymentWhereInput = {
    AND: [
      paymentScope(p),
      query.method ? { method: query.method } : {},
      query.currency ? { currencyCode: query.currency } : {},
      query.invoiceId ? { invoiceId: query.invoiceId } : {},
      query.customerId ? { invoice: { order: { customerId: query.customerId } } } : {},
      query.from ? { paymentDate: { gte: new Date(query.from + "T00:00:00Z") } } : {},
      query.to ? { paymentDate: { lte: new Date(query.to + "T00:00:00Z") } } : {},
      query.q
        ? {
            OR: [
              { reference: { contains: query.q, mode: "insensitive" } },
              { invoice: { invoiceNumber: { contains: query.q, mode: "insensitive" } } },
              { invoice: { order: { customer: { businessName: { contains: query.q, mode: "insensitive" } } } } },
              { invoice: { order: { customer: { nipt: { contains: query.q.replace(/\s+/g, ""), mode: "insensitive" } } } } },
            ],
          }
        : {},
    ],
  };
  const db = getDb();
  const [rows, total] = await db.$transaction([
    db.payment.findMany({
      where,
      orderBy: [{ [query.sort]: query.dir }, { createdAt: "desc" }, { id: "asc" }],
      ...skipTake(query.page, query.pageSize),
      select: {
        ...PAYMENT_SELECT,
        invoice: {
          select: {
            invoiceNumber: true,
            status: true,
            order: { select: { id: true, orderNumber: true, customer: { select: { id: true, businessName: true, nipt: true } } } },
          },
        },
      },
    }),
    db.payment.count({ where }),
  ]);
  const sums = await db.payment.groupBy({ by: ["currencyCode"], where, _sum: { amount: true }, _count: { _all: true }, orderBy: { currencyCode: "asc" } });
  return {
    ...paged(
      rows.map((r) => ({
        ...serialize(r, p),
        invoiceNumber: r.invoice.invoiceNumber,
        invoiceStatus: r.invoice.status,
        order: { id: r.invoice.order.id, orderNumber: r.invoice.order.orderNumber },
        customer: r.invoice.order.customer,
      })),
      total,
      query.page,
      query.pageSize,
    ),
    /** Per currency, over the whole filtered set. */
    totals: sums.map((s) => ({ currencyCode: s.currencyCode, count: s._count._all, amount: D(s._sum.amount ?? 0).toFixed(2) })),
  };
}

/** One payment with its invoice's balance, before and after it. */
export async function getPayment(p: Principal, paymentId: string) {
  assertPermission(p, "payments.view");
  const db = getDb();
  const row = await db.payment.findFirst({
    where: { AND: [{ id: paymentId }, paymentScope(p)] },
    select: {
      ...PAYMENT_SELECT,
      invoice: {
        select: {
          id: true,
          invoiceNumber: true,
          status: true,
          total: true,
          dueDate: true,
          payments: { select: { id: true, amount: true }, orderBy: [{ paymentDate: "asc" }, { createdAt: "asc" }] },
          order: { select: { id: true, orderNumber: true, customer: { select: { id: true, businessName: true, nipt: true } } } },
        },
      },
    },
  });
  if (!row) throw notFound("Payment");
  const inv = row.invoice;
  let before = D(0);
  for (const x of inv.payments) {
    if (x.id === row.id) break;
    before = before.plus(x.amount);
  }
  const paidNow = inv.payments.reduce((s, x) => s.plus(x.amount), D(0));
  const b = deriveInvoiceStatus(inv, paidNow, businessDate());
  return {
    ...serialize(row, p),
    invoice: {
      id: inv.id,
      invoiceNumber: inv.invoiceNumber,
      status: inv.status,
      total: inv.total.toFixed(2),
      paid: b.paid.toFixed(2),
      outstanding: b.outstanding.toFixed(2),
      paymentStatus: b.paymentStatus,
      overdue: b.overdue,
    },
    /** Invoice balance immediately before and after this payment. */
    balanceBefore: inv.total.minus(before).toFixed(2),
    balanceAfter: inv.total.minus(before).minus(row.amount).toFixed(2),
    order: { id: inv.order.id, orderNumber: inv.order.orderNumber },
    customer: inv.order.customer,
  };
}

/* ------------------------------------------------------------- record */

/**
 * Records a payment in the invoice currency.
 *
 * Integrity:
 * - The guard trigger (payment_guard) is the authority for "invoice is ISSUED",
 *   currency match and "no overpayment". It locks the invoice row, so concurrent
 *   payments are serialized. The checks here only give clearer messages first.
 * - The transaction runs SERIALIZABLE; a serialization failure (40001) or
 *   deadlock is retried a bounded number of times. Other errors are not retried.
 * - Idempotency: the same idempotencyKey returns the original payment
 *   (replayed: true) instead of inserting a second one, also when the first
 *   attempt committed but its response was lost. Reusing a key for a different
 *   payment is a 409.
 * - Payments are immutable: the trigger refuses UPDATE and DELETE.
 */
export async function recordPayment(p: Principal, input: RecordPaymentInput, retry?: RetryOptions) {
  assertPermission(p, "payments.record");
  const db = getDb();

  const previous = await findByKey(p, input.idempotencyKey, input);
  if (previous) return previous;

  const invoice = await db.invoice.findFirst({
    where: { AND: [{ id: input.invoiceId }, invoiceScope(p)] },
    select: { id: true, status: true, currencyCode: true, total: true, issueDate: true, invoiceNumber: true, payments: { select: { amount: true } } },
  });
  if (!invoice) throw notFound("Invoice");
  if (input.currencyCode && input.currencyCode !== invoice.currencyCode) {
    throw invalid(`Payments are recorded in the invoice currency (${invoice.currencyCode}).`, {
      currencyCode: [`${invoice.invoiceNumber} is in ${invoice.currencyCode}; record the payment in ${invoice.currencyCode}.`],
    });
  }
  if (invoice.status !== "ISSUED") throw conflict("INVOICE_NOT_PAYABLE", "Invoice not payable");
  const date = ymd(input.paymentDate);
  if (date > businessDate()) throw invalid("Payment date can't be in the future.", { paymentDate: ["Payment date can't be in the future."] });
  if (date < ymd(invoice.issueDate)) {
    throw invalid("Payment date can't be before the invoice was issued.", { paymentDate: [`The invoice was issued on ${ymd(invoice.issueDate)}.`] });
  }
  const outstanding = invoice.total.minus(invoice.payments.reduce((s, x) => s.plus(x.amount), D(0)));
  if (input.amount.gt(outstanding)) {
    throw new AppError(409, "OVERPAYMENT", `The amount exceeds the outstanding balance of ${outstanding.toFixed(2)} ${invoice.currencyCode}.`, {
      amount: [`At most ${outstanding.toFixed(2)} ${invoice.currencyCode}.`],
    });
  }

  try {
    const payment = await withTransactionRetry(
      () =>
        db.$transaction(
          (tx) =>
            tx.payment.create({
              data: {
                invoiceId: invoice.id,
                amount: input.amount,
                currencyCode: invoice.currencyCode,
                paymentDate: input.paymentDate,
                method: input.method,
                reference: input.reference || null,
                idempotencyKey: input.idempotencyKey,
                recordedByUserId: p.userId,
              },
              select: PAYMENT_SELECT,
            }),
          { isolationLevel: Prisma.TransactionIsolationLevel.Serializable },
        ),
      retry,
    );
    return { payment: serialize(payment, p), replayed: false };
  } catch (e) {
    if (isUniqueViolation(e, "payments_idempotency_key_key")) {
      const winner = await findByKey(p, input.idempotencyKey, input);
      if (winner) return winner;
    }
    throw mapDatabaseError(e);
  }
}

async function findByKey(p: Principal, key: string, expect?: RecordPaymentInput) {
  const row = await getDb().payment.findUnique({ where: { idempotencyKey: key }, select: PAYMENT_SELECT });
  if (!row) return null;
  // A key belonging to a payment outside the caller's scope is treated as a reuse conflict, not disclosed.
  const visible = await getDb().payment.count({ where: { AND: [{ id: row.id }, paymentScope(p)] } });
  if (!visible || (expect && (row.invoiceId !== expect.invoiceId || !row.amount.eq(expect.amount)))) {
    throw conflict("IDEMPOTENCY_KEY_REUSED", "This idempotency key was already used for a different payment.");
  }
  return { payment: serialize(row, p), replayed: true };
}

/** Who recorded a payment is audit information: shown to roles that may record payments (managers, admins). */
const seesAttribution = (p: Principal) => hasPermission(p, "payments.record");

function serialize(row: PaymentRow, p: Principal) {
  const by = row.recordedBy;
  return {
    id: row.id,
    invoiceId: row.invoiceId,
    amount: row.amount.toFixed(2),
    currencyCode: row.currencyCode,
    paymentDate: ymd(row.paymentDate),
    method: row.method,
    reference: row.reference,
    recordedAt: row.createdAt,
    /** null when hidden from the caller or when the payment predates attribution (see recordedByKnown). */
    recordedBy: seesAttribution(p) && by ? (by.employee ? `${by.employee.firstName} ${by.employee.lastName}` : by.email) : null,
    recordedByKnown: seesAttribution(p) ? !!by : null,
  };
}
